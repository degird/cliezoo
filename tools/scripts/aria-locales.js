#!/usr/bin/env node
/* eslint-disable no-console -- A command-line tool writes to the terminal. */
/**
 * Writes build/aria-locales/{locale}.js: React Aria's built-in UI strings
 * (e.g. "Clear search", "Dismiss") for one language. The bundles only
 * carry English (tools/webpack/aria-english-only.js); PHP loads the file
 * that matches the site language, so other languages cost nothing.
 *
 * Usage: node tools/scripts/aria-locales.js <plugin-dir>
 */
const {
	mkdirSync,
	readFileSync,
	readdirSync,
	writeFileSync,
	existsSync,
} = require( 'node:fs' );
const { dirname, join, relative, resolve } = require( 'node:path' );
const { createRequire } = require( 'node:module' );
const { pathToFileURL } = require( 'node:url' );

const pluginDir = resolve( process.argv[ 2 ] || '.' );
const pluginRequire = createRequire( join( pluginDir, 'package.json' ) );
const ariaRoot = join(
	dirname( pluginRequire.resolve( 'react-aria-components/package.json' ) ),
	'..',
	'react-aria'
);
const privateDir = join( ariaRoot, 'dist', 'private' );
const intlDir = join( privateDir, 'intl' );
const outDir = join( pluginDir, 'build', 'aria-locales' );

// intl folder -> package names that read it (e.g. "previewtrigger" -> "@react-aria/link-preview").
const packagesByFolder = new Map();
for ( const dir of readdirSync( privateDir ) ) {
	const full = join( privateDir, dir );
	let files;
	try {
		files = readdirSync( full ).filter( ( f ) => f.endsWith( '.mjs' ) );
	} catch {
		continue;
	}
	for ( const file of files ) {
		const source = readFileSync( join( full, file ), 'utf8' );
		const imp = /from "(\.\/|\.\.\/[a-z-]+\/)intlStrings\.mjs"/.exec(
			source
		);
		if ( ! imp ) {
			continue;
		}
		const stringsFile = resolve( full, imp[ 1 ], 'intlStrings.mjs' );
		const folder = /\/intl\/([a-z-]+)\//.exec(
			readFileSync( stringsFile, 'utf8' ).replace( /\\/g, '/' )
		)?.[ 1 ];
		if ( ! folder ) {
			continue;
		}
		for ( const [ , pkg ] of source.matchAll(
			/'(@react-aria\/[a-z-]+)'/g
		) ) {
			if ( ! packagesByFolder.has( folder ) ) {
				packagesByFolder.set( folder, new Set() );
			}
			packagesByFolder.get( folder ).add( pkg );
		}
	}
}

/**
 * Writes one file per locale. React Aria ships its strings as ES modules,
 * so they are loaded with import(), which a CommonJS script may await.
 */
async function main() {
	const { getPackageLocalizationScript } = await import(
		pathToFileURL( join( privateDir, 'i18n', 'server.mjs' ) ).href
	);
	const locales = readdirSync( join( intlDir, 'autocomplete' ) )
		.filter( ( f ) => /^[a-z]{2}-[A-Z]{2}\.mjs$/.test( f ) )
		.map( ( f ) => f.replace( '.mjs', '' ) )
		.filter( ( locale ) => locale !== 'en-US' );

	mkdirSync( outDir, { recursive: true } );
	for ( const locale of locales ) {
		const strings = {};
		for ( const [ folder, packages ] of packagesByFolder ) {
			const file = join( intlDir, folder, `${ locale }.mjs` );
			if ( ! existsSync( file ) ) {
				continue;
			}
			const { default: dict } = await import( pathToFileURL( file ).href );
			for ( const pkg of packages ) {
				strings[ pkg ] = dict;
			}
		}
		const script = `/*! React Aria strings (${ locale }), Apache-2.0, Adobe. Generated by tools/scripts/aria-locales.js (https://github.com/degird/cliezoo) from the react-aria npm package (https://github.com/adobe/react-spectrum). */\n${ getPackageLocalizationScript( locale, strings ) }\n`;
		writeFileSync( join( outDir, `${ locale }.js` ), script );
	}
	console.log(
		`aria-locales: ${ locales.length } files in ${ relative( process.cwd(), outDir ) } (${ packagesByFolder.size } string sets)`
	);
}

main().catch( ( error ) => {
	console.error( error );
	process.exitCode = 1;
} );
