<?php
/**
 * Private local storage.
 *
 * @package Cliezoo
 */

declare( strict_types=1 );

namespace Cliezoo\Infrastructure\Storage;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

// phpcs:disable WordPress.Security.EscapeOutput.ExceptionNotEscaped -- Exception messages are returned as JSON by the REST layer and never printed as HTML.

/**
 * Files live in `wp-content/uploads/cliezoo-private/{yyyy}/{mm}/{random}` (or
 * CLIEZOO_PRIVATE_DIR outside the web root) with random names, deny files
 * for Apache/IIS, and are only ever served through Policy-checked endpoints
 * or signed URLs (Blueprint §14.2).
 *
 * Streaming and chunk appends need native file functions; the WordPress
 * Filesystem API has no streaming or append support.
 *
 * phpcs:disable WordPress.WP.AlternativeFunctions
 */
final class LocalDriver implements StorageDriver {

	public const CHUNK = 5242880;

	/**
	 * Driver id.
	 *
	 * @return string
	 */
	public function id(): string {
		return 'local';
	}

	/**
	 * Label.
	 *
	 * @return string
	 */
	public function label(): string {
		return __( 'This server (private)', 'cliezoo' );
	}

	/**
	 * Capabilities.
	 *
	 * @return array{presigned_upload: bool, multipart: bool, presigned_download: bool, server_copy: bool, max_object_size: int}
	 */
	public function capabilities(): array {
		return array(
			'presigned_upload'   => false,
			'multipart'          => true,
			'presigned_download' => false,
			'server_copy'        => true,
			'max_object_size'    => 0,
		);
	}

	/**
	 * Base directory (created and protected on first use).
	 *
	 * @return string
	 */
	public static function base(): string {
		if ( defined( 'CLIEZOO_PRIVATE_DIR' ) && '' !== (string) CLIEZOO_PRIVATE_DIR ) {
			$dir = untrailingslashit( (string) CLIEZOO_PRIVATE_DIR );
		} else {
			$uploads = wp_upload_dir( null, false );
			$dir     = untrailingslashit( (string) $uploads['basedir'] ) . '/cliezoo-private';
		}
		if ( ! is_dir( $dir ) ) {
			wp_mkdir_p( $dir );
		}
		self::protect( $dir );
		return $dir;
	}

	/**
	 * Writes deny files (Apache, IIS) and an empty index.
	 *
	 * @param string $dir Directory.
	 * @return void
	 */
	public static function protect( string $dir ): void {
		$files = array(
			'.htaccess'  => "# Cliezoo private files.\n<IfModule mod_authz_core.c>\nRequire all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\nDeny from all\n</IfModule>\n",
			'index.php'  => "<?php\n// Silence is golden.\n",
			'web.config' => "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<configuration><system.webServer><authorization><deny users=\"*\" /></authorization></system.webServer></configuration>\n",
		);
		foreach ( $files as $name => $content ) {
			if ( ! file_exists( $dir . '/' . $name ) ) {
				file_put_contents( $dir . '/' . $name, $content );
			}
		}
	}

	/**
	 * Absolute path of a key (keys are generated by Cliezoo; traversal is rejected).
	 *
	 * @param string $key Object key.
	 * @return string
	 * @throws \InvalidArgumentException On an unsafe key.
	 */
	private function path( string $key ): string {
		if ( ! preg_match( '#^[A-Za-z0-9/_\-.]+$#', $key ) || str_contains( $key, '..' ) ) {
			throw new \InvalidArgumentException( 'Invalid storage key.' );
		}
		return self::local( self::base() . '/' . ltrim( $key, '/' ) );
	}

	/**
	 * A path on this server's own disk, never a URL or a stream wrapper.
	 *
	 * This driver reads and writes with PHP's file functions because the
	 * WordPress Filesystem API cannot stream or append, and uploads run to
	 * gigabytes. Those functions only ever see a path that passed here, so
	 * they never open remote content: anything remote goes through the
	 * WordPress HTTP API (SafeHttp).
	 *
	 * @param string $path Path.
	 * @return string The same path.
	 * @throws \InvalidArgumentException When it is not a local path.
	 */
	public static function local( string $path ): string {
		if ( '' === $path || wp_is_stream( $path ) || str_contains( $path, "\0" ) ) {
			throw new \InvalidArgumentException( 'Not a local file path.' );
		}
		return $path;
	}

	/**
	 * Local path of an object.
	 *
	 * @param string $key Object key.
	 * @return string|null
	 */
	public function local_path( string $key ): ?string {
		$path = $this->path( $key );
		return file_exists( $path ) ? $path : null;
	}

	/**
	 * Starts a proxied upload.
	 *
	 * @param string               $key  Object key.
	 * @param array<string, mixed> $meta Meta (unused locally).
	 * @return array<string, mixed>
	 */
	public function create_upload_session( string $key, array $meta ): array {
		$tmp = 'tmp/' . md5( $key );
		wp_mkdir_p( self::base() . '/' . $tmp );
		return array(
			'mode'       => 'proxy',
			'chunk_size' => self::CHUNK,
			'key'        => $key,
			'tmp'        => $tmp,
		);
	}

	/**
	 * Stores one chunk.
	 *
	 * @param array<string, mixed> $session Session.
	 * @param int                  $part    Part number.
	 * @param string               $data    Bytes.
	 * @return void
	 */
	public function upload_part( array $session, int $part, string $data ): void {
		$dir = self::local( self::base() . '/' . $session['tmp'] );
		if ( ! is_dir( $dir ) ) {
			wp_mkdir_p( $dir );
		}
		file_put_contents( $dir . '/part-' . str_pad( (string) $part, 6, '0', STR_PAD_LEFT ), $data ); // Local file (self::local()).
	}

	/**
	 * Parts received so far (for resuming).
	 *
	 * @param array<string, mixed> $session Session.
	 * @return int[]
	 */
	public function received_parts( array $session ): array {
		$dir   = self::base() . '/' . $session['tmp'];
		$parts = array();
		foreach ( (array) glob( $dir . '/part-*' ) as $file ) {
			$parts[] = (int) substr( basename( (string) $file ), 5 );
		}
		sort( $parts );
		return $parts;
	}

	/**
	 * Assembles the parts into the final object.
	 *
	 * @param array<string, mixed> $session Session.
	 * @param int                  $parts   Number of parts.
	 * @return array{size: int, path: string|null}
	 * @throws \RuntimeException When parts are missing.
	 */
	public function complete_upload( array $session, int $parts ): array {
		$dir    = self::local( self::base() . '/' . $session['tmp'] );
		$target = $this->path( (string) $session['key'] );
		wp_mkdir_p( dirname( $target ) );
		// The parts and the result are files in the private folder, joined
		// as streams so a large upload never has to fit in memory.
		$out = fopen( $target, 'wb' );
		if ( false === $out ) {
			throw new \RuntimeException( 'Could not write the file.' );
		}
		for ( $i = 0; $i < $parts; $i++ ) {
			$chunk = $dir . '/part-' . str_pad( (string) $i, 6, '0', STR_PAD_LEFT );
			if ( ! file_exists( $chunk ) ) {
				fclose( $out );
				wp_delete_file( $target );
				throw new \RuntimeException( 'Part ' . $i . ' is missing.' );
			}
			$in = fopen( $chunk, 'rb' );
			if ( false !== $in ) {
				stream_copy_to_stream( $in, $out );
				fclose( $in );
			}
		}
		fclose( $out );
		$this->cleanup( $session );
		return array(
			'size' => (int) filesize( $target ),
			'path' => $target,
		);
	}

	/**
	 * Removes a session's temporary parts.
	 *
	 * @param array<string, mixed> $session Session.
	 * @return void
	 */
	public function cleanup( array $session ): void {
		$dir = self::local( self::base() . '/' . $session['tmp'] );
		foreach ( (array) glob( $dir . '/part-*' ) as $file ) {
			wp_delete_file( (string) $file );
		}
		if ( is_dir( $dir ) ) {
			rmdir( $dir );
		}
	}

	/**
	 * Stores a server-side file.
	 *
	 * @param string $key  Object key.
	 * @param string $path Source path.
	 * @return int Size.
	 * @throws \RuntimeException When the copy fails.
	 */
	public function put( string $key, string $path ): int {
		$target = $this->path( $key );
		wp_mkdir_p( dirname( $target ) );
		if ( ! copy( self::local( $path ), $target ) ) {
			throw new \RuntimeException( 'Could not store the file.' );
		}
		return (int) filesize( $target );
	}

	/**
	 * Local files are always streamed through Cliezoo (no direct URLs).
	 *
	 * @param string $key         Object key.
	 * @param int    $ttl         Seconds.
	 * @param string $disposition Disposition.
	 * @param string $filename    Name.
	 * @return string|null
	 */
	public function read_url( string $key, int $ttl, string $disposition, string $filename ): ?string {
		return null;
	}

	/**
	 * Streams an object or a byte range.
	 *
	 * @param string                  $key   Object key.
	 * @param array{0:int,1:int}|null $range Range.
	 * @return void
	 */
	public function stream( string $key, ?array $range ): void {
		$path = $this->path( $key );
		// A file in the private folder, sent in 1 MB pieces with byte-range
		// support; WP_Filesystem would read all of it into memory first.
		$handle = fopen( $path, 'rb' );
		if ( false === $handle ) {
			return;
		}
		$start  = $range ? $range[0] : 0;
		$length = $range ? $range[1] - $range[0] + 1 : (int) filesize( $path );
		fseek( $handle, $start );
		while ( $length > 0 && ! feof( $handle ) ) {
			$read = min( 1048576, $length );
			echo fread( $handle, $read ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Binary file download.
			$length -= $read;
			flush();
		}
		fclose( $handle );
	}

	/**
	 * Deletes an object.
	 *
	 * @param string $key Object key.
	 * @return void
	 */
	public function delete( string $key ): void {
		$path = $this->path( $key );
		if ( file_exists( $path ) ) {
			wp_delete_file( $path );
		}
	}

	/**
	 * Copies an object.
	 *
	 * @param string $key     Source key.
	 * @param string $new_key Target key.
	 * @return void
	 */
	public function copy( string $key, string $new_key ): void {
		$target = $this->path( $new_key );
		wp_mkdir_p( dirname( $target ) );
		copy( $this->path( $key ), $target );
	}

	/**
	 * Object info.
	 *
	 * @param string $key Object key.
	 * @return array{size: int}|null
	 */
	public function head( string $key ): ?array {
		$path = $this->path( $key );
		return file_exists( $path ) ? array( 'size' => (int) filesize( $path ) ) : null;
	}

	/**
	 * Health.
	 *
	 * @return array{ok: bool, message: string}
	 */
	public function health_check(): array {
		$base = self::base();
		if ( ! wp_is_writable( $base ) ) {
			return array(
				'ok'      => false,
				'message' => __( 'The private files folder is not writable.', 'cliezoo' ),
			);
		}
		return array(
			'ok'      => true,
			'message' => __( 'Private files are stored on this server.', 'cliezoo' ),
		);
	}
}
